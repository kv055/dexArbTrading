#!/usr/bin/env bash
set -euo pipefail

# Count git-tracked text lines in the parent repository and its submodules.
# Each repo prints a total, then how much of that total is written by us vs
# external (vendored/lockfile dependencies and generated artifacts such as
# OpenAPI clients/servers, protobuf stubs, and bundled specs).

ROOT="$(cd "$(dirname "$0")/.." && pwd)"

grand_total=0
grand_ours=0
grand_external=0

is_binary() {
  local path="$1"
  local encoding

  encoding=$(file -b --mime-encoding "$path" 2>/dev/null || true)
  [ "$encoding" = "binary" ]
}

# Dependency trees, lockfiles, and generated-code conventions.
is_external_path() {
  local file="$1"

  case "$file" in
    node_modules/*|*/node_modules/*) return 0 ;;
    vendor/*|*/vendor/*) return 0 ;;
    third_party/*|*/third_party/*|third-party/*|*/third-party/*) return 0 ;;
    .terraform/*|*/.terraform/*) return 0 ;;
    go.sum|*/go.sum) return 0 ;;
    package-lock.json|*/package-lock.json) return 0 ;;
    yarn.lock|*/yarn.lock) return 0 ;;
    pnpm-lock.yaml|*/pnpm-lock.yaml) return 0 ;;
    Cargo.lock|*/Cargo.lock) return 0 ;;
    composer.lock|*/composer.lock) return 0 ;;
    Gemfile.lock|*/Gemfile.lock) return 0 ;;
    *.min.js|*.min.css) return 0 ;;
    api-docs/specs/*) return 0 ;;
    src/generated/*|*/src/generated/*|*/generated/*) return 0 ;;
    */internal/api/gen/*) return 0 ;;
    *.gen.go|*.gen.ts|*.gen.js|*.gen_test.go) return 0 ;;
    *.pb.go) return 0 ;;
  esac
  return 1
}

# Conservative header sniff for codegen that does not follow a path convention.
# Only the first lines are checked so generator *sources* (which embed these
# strings later in the file) stay classified as ours.
is_generated_header() {
  local path="$1"

  head -n 15 "$path" 2>/dev/null | grep -qiE \
    'code generated by|this file was auto-generated|this file was automatically generated|this file was generated|@generated'
}

is_external() {
  local file="$1"
  local path="$2"

  if is_external_path "$file"; then
    return 0
  fi
  is_generated_header "$path"
}

print_counts() {
  local label="$1"
  local total="$2"
  local ours="$3"
  local external="$4"

  printf "  %-40s %6d lines\n" "$label" "$total"
  printf "      %-36s %6d\n" "written by us" "$ours"
  printf "      %-36s %6d\n" "external" "$external"
}

count_loc() {
  local dir="$1"
  local label="$2"
  local total=0
  local ours=0
  local external=0
  local file path count

  if [ ! -d "$dir/.git" ] && [ ! -f "$dir/.git" ]; then
    echo "  $label: (not initialized)"
    return
  fi

  while IFS= read -r file; do
    path="$dir/$file"
    [ -f "$path" ] || continue
    if is_binary "$path"; then
      continue
    fi

    count=$(grep -c '' "$path" 2>/dev/null || true)
    total=$((total + count))
    if is_external "$file" "$path"; then
      external=$((external + count))
    else
      ours=$((ours + count))
    fi
  done < <(git -C "$dir" ls-files 2>/dev/null)

  print_counts "$label" "$total" "$ours" "$external"
  echo ""
  grand_total=$((grand_total + total))
  grand_ours=$((grand_ours + ours))
  grand_external=$((grand_external + external))
}

SUBMODULE_PATHS=$(git -C "$ROOT" submodule--helper list 2>/dev/null | awk '{print $4}' || git -C "$ROOT" config --file .gitmodules --get-regexp path | awk '{print $2}')

echo ""
echo "Lines of code per repo"
echo "External = dependencies (vendor, node_modules, lockfiles) and generated"
echo "code (OpenAPI, protobuf, bundled specs, and other codegen output)."
echo "────────────────────────────────────────────────────"

count_loc "$ROOT" "dexArbTrading (root)"

while IFS= read -r sm_path; do
  [ -n "$sm_path" ] || continue
  count_loc "$ROOT/$sm_path" "$sm_path"
done <<< "$SUBMODULE_PATHS"

echo "────────────────────────────────────────────────────"
print_counts "TOTAL" "$grand_total" "$grand_ours" "$grand_external"
echo ""
